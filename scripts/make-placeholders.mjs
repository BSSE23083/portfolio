// Generates a labeled placeholder image for every entry in src/content/images.json
// and writes content/PLACEHOLDERS.md (the list of what Abdul still needs to send).
// Run with: npm run placeholders
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const images = JSON.parse(readFileSync("src/content/images.json", "utf8"));
mkdirSync("public/placeholders", { recursive: true });

const rows = [];
for (const [name, info] of Object.entries(images)) {
  if (info.src) continue; // a real image has been supplied
  const [rw, rh] = info.ratio.split(":").map(Number);
  const w = 1600;
  const h = Math.round((w * rh) / rw);
  const size = Math.round(w / 26);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" font-family="ui-monospace, Menlo, Consolas, monospace">
  <rect width="${w}" height="${h}" fill="#20222c"/>
  <rect x="24" y="24" width="${w - 48}" height="${h - 48}" fill="none" stroke="#ffb86b" stroke-width="4" stroke-dasharray="18 14" rx="24"/>
  <text x="${w / 2}" y="${h / 2 - size * 1.1}" fill="#ffb86b" font-size="${size * 0.7}" text-anchor="middle" letter-spacing="6">PLACEHOLDER</text>
  <text x="${w / 2}" y="${h / 2 + size * 0.3}" fill="#f2ead9" font-size="${size}" text-anchor="middle">${info.label.replace(/&/g, "&amp;")}</text>
  <text x="${w / 2}" y="${h / 2 + size * 1.7}" fill="#8f8a7e" font-size="${size * 0.6}" text-anchor="middle">${name} · ${info.ratio}</text>
</svg>
`;
  writeFileSync(`public/placeholders/${name}.svg`, svg);
  rows.push(`| ${info.label} | ${info.ratio} | \`${name}\` | ${info.page} |`);
}

writeFileSync(
  "content/PLACEHOLDERS.md",
  `# Placeholders still to replace

Generated by \`npm run placeholders\`. Each row is an image the site is waiting for.

**To replace one:** put the real image in \`public/images/\` (for example \`public/images/${Object.keys(images)[0]}.jpg\`),
then add \`"src": "/images/your-file.jpg"\` to that entry in \`src/content/images.json\`.

Text placeholders are marked \`[PLACEHOLDER: ...]\` in \`src/content/site.ts\` and \`src/content/case-studies/*.mdx\`.

| What goes here | Shape | Name | Page |
|---|---|---|---|
${rows.join("\n")}
`,
);
console.log(`Wrote ${rows.length} placeholder images.`);
